#!/bin/sh
# Несколько канальных инструкций в одном такте: два ввода и два вывода
# в непересекающиеся полуинтервалы. Байты распределяются в порядке инструкций.
# Программа: (8,0x2000,LAST), (8,0x2010,LAST), (8,LAST,0x2000),
# (8,LAST,0x2010), 60 нулевых троек — затем 'AB'.
# Значения полей — в порядке байтов хоста.
# Такт 1: исполняются ранее прочитанные инструкции (загрузка, тишина);
# такт 2: ввод 'A', ввод 'B', вывод 'A', вывод 'B';
# такт 3: EOF на обоих вводах — исполнить до конца (вывод 'A', вывод 'B') и halt.
# Наружу: ABAB.
set -e
cd "$(dirname "$0")/.."
if [ ! -x ./space ]; then
  echo "нет ./space, сначала make"
  exit 1
fi
{ printf '\010\000\000\040\357\377\010\000\020\040\357\377\010\000\357\377\000\040\010\000\357\377\020\040'; head -c 360 /dev/zero; printf 'AB'; } | timeout 5 ./space > /tmp/multi_run.out
printf 'ABAB' > /tmp/multi_expected.out
cmp /tmp/multi_run.out /tmp/multi_expected.out
echo "ok: два ввода и два вывода в одном такте (ABAB)"
