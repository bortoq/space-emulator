#!/bin/sh
# Запросы состояния канала NOPами: (0,dst,LAST) — сторона чтения,
# (0,LAST,src) — сторона записи; k = 8 бит (бит 0 — конец/сбой).
# Программа: запрос, ввод, запрос, вывод, вывод, запрос, вывод + 'Q'.
# Такт 1: загрузка (тишина); такт 2: всё нули, кроме введённого 'Q';
# такт 3: конец увиден вторым запросом; такт 4: оба запроса видят конец.
# Наружу: 00 00 00 | 00 01 00 | 01 01 00.
set -e
cd "$(dirname "$0")/.."
if [ ! -x ./space ]; then
  echo "нет ./space, сначала make"
  exit 1
fi
{ printf '\000\000\000\040\357\377\010\000\020\040\357\377\000\000\040\040\357\377\010\000\357\377\000\040\010\000\357\377\040\040\000\000\357\377\060\040\010\000\357\377\060\040'; head -c 342 /dev/zero; printf 'Q'; } | timeout 5 ./space -t 4 > /tmp/state_run.out
printf '\000\000\000\000\001\000\001\001\000' > /tmp/state_expected.out
cmp /tmp/state_run.out /tmp/state_expected.out
echo "ok: запросы состояния видят конец (00 00 00, 00 01 00, 01 01 00)"
